"""What the game data still carries from elsewhere: other games, prototypes, event builds, tests.

    python -I tools/leftovers.py <base dvdroot> <update dvdroot> <out.md>

Every param row has a working name (params.Param.row_names). This reads them all and sorts out
the rows that point outside the game as sold:

* Models with no files: rows whose name gives a model (c2790, ｃ5290) that has no chrbnd in the
  game. Their names are other games' enemies (白竜シース, Seath; 薪の王, Gwyn's title).
* Marked rows: names carrying a marker of origin or status: a prototype (DS２プロト, "DS2
  prototype"), an event build (TGS版, gamescom, DLCレビュー用 "for the DLC review"), a test
  (テスト), unused (未使用), old (旧), to be deleted (削除予定), provisional (仮).
* Old system names kept for Bloodborne's own things: ダークリング (Darksign) for the Hunter's
  Mark, かがり火 (bonfire), エスト (Estus), 人間性 (humanity).

The page docs/the-leftovers.md reads the results.
"""

from __future__ import annotations

import collections
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import params

# (marker, what it means)
MARKERS = (
    ("DS２プロト", "DS2 prototype"),
    ("DS2Test", "DS2 test"),
    ("ＤＳ２", "DS2"),
    ("TGS", "Tokyo Game Show build"),
    ("gamescom", "gamescom build"),
    ("DLCレビュー用", "for the DLC review"),
    ("チャネルプロト", "channel prototype"),
    ("テスト", "test"),
    ("未使用", "unused"),
    ("削除予定", "to be deleted"),
    ("（旧）", "(old)"),
    ("（仮）", "(provisional)"),
)
# Dark Souls words for things Bloodborne renamed
OLD_NAMES = (
    ("ダークリング", "Darksign"),
    ("かがり火", "bonfire"),
    ("篝火", "bonfire"),
    ("エスト", "Estus"),
    ("人間性", "humanity"),
)
MODEL = re.compile(r"[cｃ]([0-9０-９]{4})")


def _num(s: str) -> int:
    return int(s.translate(str.maketrans("０１２３４５６７８９", "0123456789")))


def load(base: str, update: str) -> dict[str, dict[int, str]]:
    def path(rel):
        p = os.path.join(update, rel)
        return p if os.path.exists(p) else os.path.join(base, rel)

    P, _ = params.load(
        path("param/gameparam/gameparam.parambnd.dcx"),
        path("paramdef/paramdef.paramdefbnd.dcx"),
    )
    return {name: P[name].row_names() for name in sorted(P)}


def models_present(base: str, update: str) -> set[int]:
    out = set()
    for root in (base, update):
        for f in os.listdir(os.path.join(root, "chr")):
            m = re.match(r"c(\d{4})\.chrbnd\.dcx$", f)
            if m:
                out.add(int(m.group(1)))
    return out


def report(base: str, update: str) -> list[str]:
    names = load(base, update)
    have = models_present(base, update)
    total = sum(len(v) for v in names.values())
    out = [
        "# Leftovers in the game data\n",
        (
            f"Generated by `tools/leftovers.py`. The working names of all {total:,} param rows, "
            "sorted by what they point to outside the game as sold. Names are the rows' own "
            "labels; see docs/the-leftovers.md.\n"
        ),
    ]
    # 1. models with no files
    missing: dict[int, list[tuple[str, int, str]]] = collections.defaultdict(list)
    for pname, rows in names.items():
        for rid, lab in rows.items():
            m = MODEL.search(lab or "")
            if m and _num(m.group(1)) not in have:
                missing[_num(m.group(1))].append((pname, rid, lab))
    out += [
        "## Models with no files\n",
        (
            f"{sum(len(v) for v in missing.values()):,} rows name {len(missing)} models that "
            "have no chrbnd in the game. One example name for each, and where the rows are.\n"
        ),
        "| Model | Rows | Params | Example name |",
        "|---|---:|---|---|",
    ]
    for mod, rows in sorted(missing.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        per = collections.Counter(p for p, _, _ in rows)
        ex = next((lab for _, _, lab in rows if "共通攻撃" not in lab), rows[0][2])
        out.append(
            f"| c{mod:04d} | {len(rows)} | "
            + ", ".join(f"{p} {n}" for p, n in per.most_common())
            + f" | {ex.replace(chr(0x3000), ' ')} |"
        )
    # 2. marked rows
    out += [
        "\n## Marked rows\n",
        "| Marker | Meaning | Rows | Params |",
        "|---|---|---:|---|",
    ]
    found: dict[str, list[tuple[str, int, str]]] = {}
    for marker, meaning in MARKERS + OLD_NAMES:
        hits = [
            (p, rid, lab)
            for p, rows in names.items()
            for rid, lab in rows.items()
            if marker in (lab or "")
        ]
        found[marker] = hits
        per = collections.Counter(p for p, _, _ in hits)
        out.append(
            f"| {marker} | {meaning} | {len(hits)} | "
            + ", ".join(f"{p} {n}" for p, n in per.most_common(6))
            + " |"
        )
    for marker, meaning in MARKERS + OLD_NAMES:
        hits = found[marker]
        if not hits or marker == "テスト":
            continue
        out += [
            f"\n### {marker} ({meaning})\n",
            "| Param | Row | Name |",
            "|---|---:|---|",
        ]
        for p, rid, lab in hits:
            out.append(f"| {p} | {rid} | {lab.replace(chr(0x3000), ' ')} |")
    tests = found["テスト"]
    out += [
        "\n### テスト (test)\n",
        f"{len(tests)} rows; by param: "
        + ", ".join(
            f"{p} {n}"
            for p, n in collections.Counter(p for p, _, _ in tests).most_common()
        )
        + ".\n",
    ]
    return out


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    a = sys.argv
    if len(a) != 4:
        print(__doc__)
        return 2
    lines = report(a[1], a[2])
    os.makedirs(os.path.dirname(os.path.abspath(a[3])), exist_ok=True)
    with open(a[3], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} lines -> {a[3]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
