"""Special effects: what blood gems and New Game+ actually change, from SpEffectParam.

    python -I tools/effects.py tables <base dvdroot> <update dvdroot> <out dir>
    python -I tools/effects.py effect <base dvdroot> <update dvdroot> <SpEffectParam row> ...

`tables` writes gems.md (every blood gem effect: the game's text beside the numbers its special
effect holds) and ngplus.md (the New Game+ effects and the enemies that use them). `effect`
prints what given SpEffectParam rows change.

How they connect (docs/the-combat.md, "Effects"):

* GemeffectParam: one row per possible gem effect, with its special effect (speffectId), its
  category (GemCategoryParam), its rank and the ranks it can drop at. Its text is the row of the
  same id in the menu text's 魔石効果 ("gem effect") table.
* SpEffectParam: the effect itself, 228 fields. A field "changes" when it differs from the value
  most rows hold (1.0 for a rate, 0 or -1 for most others).
* NpcParam.GameClearSpEffectID: the effect a character gets in New Game+. Those effects have
  bGameClearBonus (周回ボーナス用か, "for the cycle bonus?") set, and the game scales them by the
  cycle: 1.0, 1.07, 1.1, 1.125, 1.15, 1.2 from the first to the sixth repeat (table at 04b31ed0
  in the 1.09 executable), and not at all in the first playthrough.
"""

from __future__ import annotations

import collections
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import items as itemlib
import souls

# The New Game+ multiplier by playthrough (04b31ed0): index 0 is the first game (no effect).
CYCLE = (None, 1.0, 1.07, 1.1, 1.125, 1.15, 1.2)


class Effects:
    def __init__(self, w: itemlib.World):
        self.w = w
        self.rows = w.rows("SpEffectParam")
        self.base = {
            f: collections.Counter(r[f] for r in self.rows.values()).most_common(1)[0][
                0
            ]
            for f in next(iter(self.rows.values()))
        }
        self.text: dict[int, str] = {}
        for b in souls.bnd4_read(souls.load(w.path("msg/engus/menu.msgbnd.dcx"))):
            if "魔石効果" in b.name:
                self.text = {
                    k: v.replace("\n", " ")
                    for k, v in souls.fmg_read(b.data).items()
                    if v and v.strip()
                }

    def changes(self, sid: int, skip: tuple[str, ...] = ()) -> dict:
        r = self.rows.get(sid)
        if r is None:
            return {}
        return {
            k: v
            for k, v in r.items()
            if v != self.base[k]
            and k not in skip
            and not k.startswith(("dmgLv_", "effectTarget", "vowType"))
        }


def show(field: str, value) -> str:
    """A changed value, rates as percentages."""
    if isinstance(value, float) and re.search(r"Rate|rate", field):
        return f"{field} ×{value:g} ({(value - 1) * 100:+.2f}%)"
    return f"{field} {value:g}" if isinstance(value, float) else f"{field} {value}"


# fields that say how an effect is filed, shown or targeted, not what it does
BOOKKEEPING = (
    "spCategory",
    "categoryPriority",
    "saveCategory",
    "iconId",
    "sortId",
    "magParamChange",
    "miracleParamChange",
    "enableEquipSlotCheck",
    "useSpEffectEffect",
    "dispIconNonactive",
)


def gems(ef: Effects) -> list[str]:
    g = ef.w.rows("GemeffectParam")
    cats = ef.w.rows("GemCategoryParam")
    by_cat: dict[int, list[int]] = collections.defaultdict(list)
    for gid, r in sorted(g.items()):
        if r["speffectId"] > 0 and gid in ef.text:
            by_cat[r["categoryId"]].append(gid)
    out = [
        "# Blood gem effects\n",
        (
            "Generated by `tools/effects.py tables`. Each category's effects by rank: the game's "
            "own text (魔石効果), and what the effect's SpEffectParam row actually changes. Rates "
            'are multipliers; the text rounds them, and the flat "Add … ATK" values are whole '
            "numbers in the data.\n"
        ),
    ]
    for cat in sorted(by_cat):
        c = cats.get(cat, {})
        neg = " (negative)" if c.get("isNegative") else ""
        out.append(f"\n## Category {cat}{neg}\n")
        out.append("| Gem effect | Rank | Drops at ranks | Text | Changes |")
        out.append("|---:|---:|---|---|---|")
        for gid in by_cat[cat]:
            r = g[gid]
            ch = ef.changes(r["speffectId"], BOOKKEEPING)
            atk = (
                f"; on hit: SpEffect {r['speffectId_forAtk']}"
                if r["speffectId_forAtk"] > 0
                else ""
            )
            out.append(
                f"| {gid} | {r['effectRank']} | {r['rankMin']}–{r['rankMax']} | "
                f"{ef.text[gid]} | {', '.join(show(k, v) for k, v in ch.items()) or '—'}{atk} |"
            )
    return out


NG_FIELDS = (
    ("maxHpRate", "HP"),
    ("physicsAttackPowerRate", "attack"),
    ("physicsDiffenceRate", "defense"),
    ("staminaAttackRate", "stamina damage"),
    ("haveSoulRate", "echoes"),
)


def ngplus(ef: Effects) -> list[str]:
    users: dict[int, list[int]] = collections.defaultdict(list)
    for nid, r in sorted(ef.w.npcs.items()):
        if r["GameClearSpEffectID"] > 0:
            users[r["GameClearSpEffectID"]].append(nid)
    out = [
        "# New Game+ effects\n",
        (
            "Generated by `tools/effects.py tables`. Each NpcParam row names its New Game+ special "
            "effect (GameClearSpEffectID). These effects are flagged bGameClearBonus: they do "
            "nothing in the first playthrough, and from the second on the game multiplies them by "
            "the playthrough's factor (×1.0, ×1.07, ×1.1, ×1.125, ×1.15, ×1.2 from the sixth).\n"
        ),
        "| Effect | HP | Attack | Defense | Stamina damage | Echoes | Other | NpcParam rows | Named |",
        "|---:|---:|---:|---:|---:|---:|---|---:|---|",
    ]
    for sid in sorted(k for k, r in ef.rows.items() if r["bGameClearBonus"]):
        r = ef.rows[sid]
        other = ef.changes(
            sid,
            BOOKKEEPING
            + ("bGameClearBonus", "enableEquipSlotCheck")
            + tuple(f for f, _ in NG_FIELDS)
            # the elements' rates are left out only where they equal the physical one
            + tuple(
                f
                for f, same in (
                    ("magicAttackPowerRate", "physicsAttackPowerRate"),
                    ("fireAttackPowerRate", "physicsAttackPowerRate"),
                    ("thunderAttackPowerRate", "physicsAttackPowerRate"),
                    ("magicDiffenceRate", "physicsDiffenceRate"),
                    ("fireDiffenceRate", "physicsDiffenceRate"),
                    ("thunderDiffenceRate", "physicsDiffenceRate"),
                )
                if r[f] == r[same]
            ),
        )
        names = sorted(
            {
                n
                for n in (
                    ef.w.npc_names.get(ef.w.npcs[x]["nameId"], "").strip()
                    for x in users.get(sid, ())
                )
                if n
            }
        )
        out.append(
            f"| {sid} | "
            + " | ".join(f"×{r[f]:g}" for f, _ in NG_FIELDS)
            + f" | {', '.join(show(k, v) for k, v in other.items())} | "
            f"{len(users.get(sid, []))} | {', '.join(names[:6])}{' …' if len(names) > 6 else ''} |"
        )
    return out


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    a = sys.argv
    if len(a) < 5 or a[1] not in ("tables", "effect"):
        print(__doc__)
        return 2
    ef = Effects(itemlib.World(a[2], a[3]))
    if a[1] == "effect":
        for x in a[4:]:
            ch = ef.changes(int(x))
            print(
                f"{x}: "
                + (
                    ", ".join(show(k, v) for k, v in ch.items())
                    or "no row / no changes"
                )
            )
        return 0
    os.makedirs(a[4], exist_ok=True)
    for name, lines in (("gems.md", gems(ef)), ("ngplus.md", ngplus(ef))):
        with open(os.path.join(a[4], name), "w", encoding="utf-8", newline="\n") as fo:
            fo.write("\n".join(lines) + "\n")
    print(f"gems.md, ngplus.md -> {a[4]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
