"""Status buildup: slow poison, rapid poison, frenzy and beasthood, from the effects and curves.

    python -I tools/status.py tables <base dvdroot> <update dvdroot> <out dir>
    python -I tools/status.py resist <base dvdroot> <update dvdroot> <endurance> <insight> [<armor piece>...]

`tables` writes status.md: the resistance curves, the conditions themselves, what builds them
up (the player's items and gems, the enemies' attacks) and every enemy's resistances. `resist`
prints a hunter's four resistances.

How it works (docs/the-combat.md, "Status buildup"):

* Buildup is carried by special effects. On a hit, an effect adds its poizonAttackPower,
  registBlood, registCurse or registTherianthrope to the target's gauge for that condition
  ("the value added to the target's [poison resistance value] when it hits", in the field's own
  words). The condition sets in when the gauge reaches the target's resistance.
* The names are the old games'. The menu's own rows (MenuPropertySpecParam 410-413) show
  毒耐性 "poison resistance" as Slow Poison, 出血耐性 "bleeding resistance" as Rapid Poison,
  発狂耐性 "frenzy resistance" (the old curse slot) as Frenzy, and 獣化耐性 as Beasthood. A fifth
  slot, 疫病/猛毒 ("plague", "deadly poison", registIllness), has effects but no menu row and no
  player resistance.
* A hunter's resistance (01e97e90, 01e97fd0, 01e98110, 01e98250 in the 1.09 executable): the
  four armor pieces' resistPoison / resistBlood / resistCurse / resistTherianthrope (times
  their ReinforceParamProtector rate, 1.0 for every piece), plus a flat amount from effects,
  plus a stat curve: 110 (Slow Poison) and 112 (Rapid Poison) of Endurance, 113 (Frenzy) and
  114 (Beasthood) of the value at +0x124 of the stat block, very likely Insight.
* An enemy's resistance is NpcParam resist_poison / resist_blood / resist_curse.
"""

from __future__ import annotations

import collections
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat
import items as itemlib

# (effect field, armor field, NpcParam field, curve, name)
CONDITIONS = (
    ("poizonAttackPower", "resistPoison", "resist_poison", 110, "slow poison"),
    ("registBlood", "resistBlood", "resist_blood", 112, "rapid poison"),
    ("registCurse", "resistCurse", "resist_curse", 113, "frenzy"),
    ("registTherianthrope", "resistTherianthrope", "", 114, "beasthood"),
)
UNSHOWN = ("registIllness", "deadly poison (no menu row)")
BUILDUP = tuple((c[0], c[4]) for c in CONDITIONS) + (UNSHOWN,)


def buildup(effect: dict | None) -> list[tuple[str, int]]:
    """[(condition, amount)] an effect adds on a hit; negative amounts (cures) are left out."""
    if not effect:
        return []
    return [(name, effect[f]) for f, name in BUILDUP if effect[f] > 0]


def describe(effects: dict, ids) -> str:
    return ", ".join(
        f"{name} +{v}" for i in ids if i > 0 for name, v in buildup(effects.get(i))
    )


def resistances(
    w: itemlib.World, endurance: int, insight: int, pieces: list[dict]
) -> dict[str, float]:
    """A hunter's resistances without effects: armor plus the stat curve."""
    g = w.rows("CalcCorrectGraph")
    out = {}
    for _, armor, _, curve, name in CONDITIONS:
        stat = endurance if curve in (110, 112) else insight
        out[name] = sum(p[armor] for p in pieces) + combat.curve(g[curve], stat)
    return out


def tables(w: itemlib.World) -> list[str]:
    e = w.rows("SpEffectParam")
    en = w.row_names("SpEffectParam")
    g = w.rows("CalcCorrectGraph")
    out = [
        "# Status buildup\n",
        "Generated by `tools/status.py tables`. Names in Japanese are the rows' own labels.\n",
        "## A hunter's resistance from stats\n",
        "Curve value at each stat; the armor pieces' values are added to it.\n",
        "| Stat | Slow Poison (110, Endurance) | Rapid Poison (112, Endurance) | Frenzy (113, Insight) | Beasthood (114, Insight) |",
        "|---:|---:|---:|---:|---:|",
    ]
    for x in (0, 1, 5, 10, 15, 20, 30, 40, 50, 60, 70, 80, 99):
        cells = [
            f"{combat.curve(g[c], x):.1f}" if (x > 0 or c in (113, 114)) else ""
            for c in (110, 112, 113, 114)
        ]
        out.append(f"| {x} | " + " | ".join(cells) + " |")

    out += [
        "\n## The conditions' effects\n",
        (
            "Each effect that builds up a condition also says what the condition does: "
            "`changeHpRate` is a percentage of max HP and `changeHpPoint` a number of points, per "
            "tick; `motionInterval` is the tick and `effectEndurance` the duration, in seconds.\n"
        ),
        "| Effect | Label | Builds up | Duration | Tick | % max HP | Points |",
        "|---:|---|---|---:|---:|---:|---:|",
    ]
    for k in sorted(e):
        r = e[k]
        b = buildup(r)
        if not b or k >= 10000 or not (r["changeHpRate"] or r["changeHpPoint"]):
            continue
        out.append(
            f"| {k} | {en.get(k, '').replace(chr(0x3000), ' ')} | "
            f"{', '.join(f'{n} +{v}' for n, v in b)} | {r['effectEndurance']:g} | "
            f"{r['motionInterval']:g} | {r['changeHpRate']:g} | {r['changeHpPoint']} |"
        )
    out += [
        (
            "\nFrenzy's own damage is in effects without buildup, "
            '発狂ダメージ　本体 ("frenzy damage, main body"):\n'
        ),
        "| Effect | Label | Duration | Tick | % max HP |",
        "|---:|---|---:|---:|---:|",
    ]
    for k in sorted(e):
        lab = en.get(k, "")
        if "発狂" in lab and e[k]["changeHpRate"] and k < 10000:
            r = e[k]
            out.append(
                f"| {k} | {lab.replace(chr(0x3000), ' ')} | {r['effectEndurance']:g} | "
                f"{r['motionInterval']:g} | {r['changeHpRate']:g} |"
            )

    # the player's sources
    out += [
        "\n## What a hunter can inflict\n",
        "| Source | Row | Label | Builds up |",
        "|---|---:|---|---|",
    ]
    bullets = w.rows("Bullet")
    bn = w.row_names("Bullet")
    for k, r in sorted(bullets.items()):
        if k >= 1000:
            continue
        d = describe(e, (r[f"spEffectId{i}"] for i in range(5)))
        if d:
            out.append(
                f"| bullet | {k} | {bn.get(k, '').replace(chr(0x3000), ' ')} | {d} |"
            )
    gems = w.rows("GemeffectParam")
    per: dict[str, list[int]] = collections.defaultdict(list)
    for r in gems.values():
        for name, v in buildup(e.get(r["speffectId_forAtk"])):
            per[name].append(v)
    for name, vals in sorted(per.items()):
        out.append(
            f"| blood gems (on hit) | | {len(vals)} gem effects | {name} +{min(vals)} to +{max(vals)} |"
        )
    ws = combat.Weapons(w)
    for k in ws.families():
        r = ws.rows[k]
        d = describe(e, (r[f"spEffectBehaviorId{i}"] for i in range(3)))
        if d:
            out.append(f"| weapon {ws.name(k)} | {k} | | {d} |")

    # enemies
    import enemies as enemylib

    en_ = enemylib.Enemies(w)
    out += [
        "\n## Enemies\n",
        (
            "Each enemy's resistances (NpcParam, first row of each model and behavior variation) "
            "and the conditions its attacks build up (the attack rows' and bullets' effects).\n"
        ),
        "| Enemy | Row | Slow Poison | Rapid Poison | Frenzy | Its attacks build up |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for (model, var), rows in sorted(
        en_.groups().items(), key=lambda kv: (en_.name(kv[1][0]), kv[0])
    ):
        anims = en_.animations(model)
        if not anims:
            continue
        found: dict[str, int] = {}
        for hits in anims.values():
            for _, judge in hits:
                for name, v in en_.status(var, judge):
                    found[name] = max(found.get(name, 0), v)
        n = w.npcs[rows[0]]
        out.append(
            f"| {en_.name(rows[0])} | {rows[0]} | {n['resist_poison']} | {n['resist_blood']} | "
            f"{n['resist_curse']} | "
            + ", ".join(f"{k} up to +{v}" for k, v in sorted(found.items()))
            + " |"
        )
    return out


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    a = sys.argv
    if len(a) < 5 or a[1] not in ("tables", "resist"):
        print(__doc__)
        return 2
    w = itemlib.World(a[2], a[3])
    if a[1] == "resist":
        if len(a) < 6:
            print(__doc__)
            return 2
        armor = w.rows("EquipParamProtector")
        names = w.names.get("EquipParamProtector", {})
        pieces = []
        for want in a[6:]:
            rid = next(
                (
                    k
                    for k, v in sorted(names.items())
                    if (v or "").strip() == want and k in armor
                ),
                None,
            )
            if rid is None:
                print(f"no armor piece {want!r}")
                return 1
            pieces.append(armor[rid])
        res = resistances(w, int(a[4]), int(a[5]), pieces)
        print(
            f"Endurance {a[4]}, Insight {a[5]}; armor: {', '.join(a[6:]) or 'none'}\n"
            + "\n".join(f"{k:13} {v:.1f}" for k, v in res.items())
        )
        return 0
    os.makedirs(a[4], exist_ok=True)
    with open(
        os.path.join(a[4], "status.md"), "w", encoding="utf-8", newline="\n"
    ) as f:
        f.write("\n".join(tables(w)) + "\n")
    print(f"status.md -> {a[4]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
